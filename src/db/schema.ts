export const test = pgTable(
  "test",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }), // secondary key
    wpm: integer("wpm").notNull(),
    rawWpm: integer("raw_wpm").notNull(),
    accuracy: integer("accuracy").notNull(),
    consistency: real("consistency").notNull(),
    correctChars: integer("correct_chars").notNull(),
    incorrectChars: integer("incorrect_chars").notNull(),
    extraChars: integer("extra_chars").notNull(),
    missedChars: integer("missed_chars").notNull(),
    mode: text("mode", { enum: ["time", "words"] }).notNull(),
    testLength: integer("test_length").notNull(), // time => secs | words => num of words
    createdAt: timestamp("created_at").defaultNow().notNull(),
  },
  //index => index by userid sort by the created by
  (table) => [
    index("test_userId_createdAt_idx").on(table.userId, table.createdAt),
  ],
);

export const testRelations = relations(test, ({ one }) => ({
  user: one(user, { fields: [test.userId], references: [user.id] }),
}));

export const userRelations = relations(user, ({ many }) => ({
  sessions: many(session),
  accounts: many(account),
  tests: many(test),
}));

export const sessionRelations = relations(session, ({ one }) => ({
  user: one(user, {
    fields: [session.userId],
    references: [user.id],
  }),
}));

export const accountRelations = relations(account, ({ one }) => ({
  user: one(user, {
    fields: [account.userId],
    references: [user.id],
  }),
}));
